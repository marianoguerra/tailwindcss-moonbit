// Embeds web/site/assets/margaui-bundle.json into bundle_data.mbt as MoonBit
// raw string literals, so the wasm build carries margaui with nothing to load.
// Output is deterministic (imports sorted by path); the file is committed so a
// fresh checkout type-checks without running this.
//
//   node web/margaui/gen.mjs           # regenerate
//   node web/margaui/gen.mjs --check   # fail if bundle_data.mbt is stale
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const target = join(here, 'bundle_data.mbt')
const bundle = JSON.parse(readFileSync(join(here, '../site/assets/margaui-bundle.json'), 'utf8'))

// `#|` lines are raw: no escapes or interpolation, so the CSS goes in verbatim.
// The layout is exactly what `moon fmt` produces, so formatting is a no-op and
// `--check` stays meaningful.
const literal = (text, indent) =>
  text
    .split('\n')
    .map((line) => indent + '#|' + line + '\n')
    .join('')

let out = '// Generated by gen.mjs from ../site/assets/margaui-bundle.json. Do not edit.\n\n'
out += '///|\nlet entry_css : String =\n' + literal(bundle.css, '  ') + '\n'
out += '///|\nlet imports : Array[(String, String)] = [\n'
for (const path of Object.keys(bundle.imports).sort()) {
  out += `  (\n    ${JSON.stringify(path)},\n    (\n` + literal(bundle.imports[path], '      ') + '    ),\n  ),\n'
}
out += ']\n'

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) {
    console.error('web/margaui/bundle_data.mbt is stale; run `just margaui-gen`')
    process.exit(1)
  }
} else {
  writeFileSync(target, out)
}
